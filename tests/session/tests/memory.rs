// Peak ceiling for compaction at the original four-message cap (programming-model.md, section 6.3).
const FOUR_MESSAGES_TOOL_CEILING: u64 = 86_000;

// Peak ceiling for four-message compaction with an invalid call (programming-model.md, section 6.3).
const FOUR_MESSAGES_INVALID_CEILING: u64 = 85_000;

// Peak ceiling for four-message compaction with a talk result (programming-model.md, section 6.3).
const FOUR_MESSAGES_TALK_CEILING: u64 = 84_000;

#[test]
fn the_four_message_cap_asks_for_compaction_before_provider_growth() {
    let original = Limits { history_messages: 4, ..LIMITS };
    for (route, bound) in [
        (Route::Tool, FOUR_MESSAGES_TOOL_CEILING),
        (Route::Invalid, FOUR_MESSAGES_INVALID_CEILING),
        (Route::Talk, FOUR_MESSAGES_TALK_CEILING),
    ] {
        let (mut limits, _, output, field) = pressure_limits(&original, route, original.history_messages);
        limits.history_messages = original.history_messages;
        assert_eq!(limits.history_messages - 3, 1, "one cell cannot hold an assistant and its results");
        let env = Env { now: Time::ZERO, wall: Wall::EPOCH, limits };
        let mut out = Queue::with_capacity(max_out(&limits));
        let meter = Meter::new();
        let mut domain = Domain::new(&limits, 15);
        let seen = measured_step(
            &mut domain,
            &env,
            &mut out,
            &meter,
            bound,
            Event::Open { opener: Token::new(1), opening: zero_opening(fill_spec(&limits)) },
        );
        let owner = seen.complete.expect("initial original message count admits");
        let seen = match route {
            Route::Tool => {
                let seen = measured_step(
                    &mut domain,
                    &env,
                    &mut out,
                    &meter,
                    bound,
                    Event::Completed { owner, completion: read_completion(1) },
                );
                let op = seen.io[0].expect("original full generated read admits its IO right");
                measured_step(
                    &mut domain,
                    &env,
                    &mut out,
                    &meter,
                    bound,
                    Event::Done { owner: op, done: Done::Loaded { content: bytes(output), version: VERSION } },
                )
            }
            Route::Invalid => {
                let seen = measured_step(
                    &mut domain,
                    &env,
                    &mut out,
                    &meter,
                    bound,
                    Event::Completed { owner, completion: missing_completion(field) },
                );
                assert!(seen.complete.is_none() && seen.end.is_none());
                domain.reclaim();
                measured_resume(&mut domain, &env, &mut out, &meter, bound)
            }
            Route::Talk => {
                let block = size(size_of::<Block>());
                let spec_cost = 2 + 2 * size(size_of::<Descriptor>()) + block + 2 + 26 + 23;
                let message = original.history_bytes - spec_cost - block - 1 - block;
                let seen = measured_step(
                    &mut domain,
                    &env,
                    &mut out,
                    &meter,
                    bound,
                    Event::Completed {
                        owner,
                        completion: Completion {
                            reasoning_dropped: Box::default(),
                            content: Box::new([Block::Text { text: bytes(1), replay: None }]),
                            stop: Stop::EndTurn,
                            usage: Usage::ZERO,
                        },
                    },
                );
                assert_eq!((seen.used, seen.turns, seen.yielded), (1, 1, 1));
                measured_step(
                    &mut domain,
                    &env,
                    &mut out,
                    &meter,
                    bound,
                    Event::Continue { session: owner, content: bytes(message) },
                )
            }
        };
        assert_eq!(seen.complete, Some(owner), "one remaining message holds the summary instruction");
        assert_eq!(seen.end, None);
        measured_step(&mut domain, &env, &mut out, &meter, bound, Event::UnsentClosed { owner });
    }
}


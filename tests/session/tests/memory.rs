/// What a step asked for last, without the payload.
enum Asked {
    Complete { owner: Token },
    Io { owner: Token },
    Other,
}

/// How a session fills its bytes.
#[derive(Clone, Copy, Debug)]
enum Route {
    /// The LLM calls a tool, whose output fills the rest.
    Tool,
    /// The LLM makes a call that cannot be decoded, whose problem, and the
    /// answer that repeats it, fill the rest.
    Invalid,
    /// The LLM yields, and the opener's next message fills the rest.
    Talk,
}

/// Source-derived caps for original payload generation; explicit credit and
/// message-cell envelopes replace V1's ignored receiving provisions.
fn pressure_limits(original: &Limits, route: Route, messages: u32) -> (Limits, u64, u64, u64) {
    let pressure = original.history_bytes;
    let block = size(size_of::<Block>());
    let part = size(size_of::<Part>());
    let spec_cost = 2 + 2 * size(size_of::<Descriptor>()) + block + 2 + 26 + 23;
    let tooling_cost = block + 3 + part + 1 + block + 1;
    let output = pressure.checked_sub(spec_cost + tooling_cost).expect("original full Tool payload fits");
    let field =
        pressure.checked_sub(spec_cost + block + 3 + block + 1).expect("original full Invalid payload fits") / 2;
    let completion_bytes = match route {
        Route::Tool => block + 3 + part + 1,
        Route::Invalid => block + 3 + field,
        Route::Talk => block + 1,
    };
    // The original 1MiB provision was never generated by this driver: its
    // actual read payload was exactly `output`. Retain that exact maximum here;
    // a separate refusal control keeps the former 1MiB receiving promise.
    let tools = smith_domain_tools::Limits {
        kits: original.sessions,
        calls: original.parallel_tools.max(original.tools.calls),
        read_bytes: u32::try_from(output).expect("original read maximum fits"),
        ..original.tools
    };
    let mut limits = Limits {
        tools,
        completion_bytes,
        // This scripted completion owns its pressure-derived invalid field/ID.
        // Its joint answer bound follows that actual payload, rather than the
        // unrelated small constant on the outer fixture.
        answer_bytes: completion_bytes,
        completion_blocks: original.parallel_tools,
        // A second provider turn may contain calls: its assistant and results
        // need two message cells even when the old V1 driver expected one.
        history_messages: original.history_messages.max(messages),
        ..*original
    };
    let envelope = reservation_envelope(&limits).expect("checked provider and whole-batch bounds");
    let headroom = size(size_of::<Block>()) + 256 * u64::from(limits.completion_blocks);
    limits.history_bytes = pressure.checked_add(envelope + headroom).expect("bounded payload and admission room");
    (limits, spec_cost, output, field)
}

/// Observe co-emitted boundary records without replacing an outstanding
/// provider/IO request, then drop receiver-owned payload copies before metering.
fn observe_fill(out: &mut Queue<Request>, observed: &mut [(bool, u32, u32, u32, bool)]) -> Option<Asked> {
    let mut asked = None;
    while let Some(request) = out.pop() {
        match request {
            Request::JobsCancelled { .. } => {}
            Request::Complete { owner, .. } => {
                assert!(asked.is_none() || matches!(asked, Some(Asked::Other)));
                asked = Some(Asked::Complete { owner });
            }
            Request::Io { owner, .. } => {
                assert!(asked.is_none() || matches!(asked, Some(Asked::Other)));
                asked = Some(Asked::Io { owner });
            }
            Request::Opened { opener, .. } => {
                let row = &mut observed[usize::try_from(opener.raw()).expect("bounded opener")];
                assert!(!row.0, "one opening per original full-payload fixture");
                row.0 = true;
            }
            Request::Used { opener, usage } => {
                assert_eq!(usage, Usage::ZERO);
                observed[usize::try_from(opener.raw()).expect("bounded opener")].1 += 1;
            }
            Request::Turn { opener, turn } => {
                let row = &mut observed[usize::try_from(opener.raw()).expect("bounded opener")];
                row.2 += 1;
                assert_eq!(
                    (turn.version, turn.endpoint, turn.dialect, turn.sequence),
                    (smith_domain_session::record::VERSION, Some(Endpoint(0)), 2, row.2)
                );
                assert_eq!((turn.usage, turn.spent), (Usage::ZERO, 0));
                assert_eq!(row.1, row.2, "every actual accepted completion emits concrete history");
                for message in &turn.messages {
                    for block in &message.content {
                        if let Block::ToolCall { call, .. } = block {
                            assert_eq!(*call, Decoded::Historical, "emitted copies retain no live authority");
                        }
                    }
                }
            }
            Request::Priced { opener, spent, own_spent } => {
                assert_eq!((spent, own_spent), (0, 0));
                observed[usize::try_from(opener.raw()).expect("bounded opener")].3 += 1;
            }
            Request::Yielded { .. } => {
                if asked.is_none() {
                    asked = Some(Asked::Other);
                }
            }
            Request::Ended { .. } => panic!("maximum payload is held for compaction, not ended"),
            Request::Cancel { .. }
            | Request::Yield { .. }
            | Request::Job { .. }
            | Request::CancelIo { .. }
            | Request::Delegate { .. }
            | Request::Withdraw { .. } => {
                panic!("the maximum-payload driver has no other terminal rights")
            }
        }
    }
    asked
}

/// Preserve each original exact payload pressure and fill route, with an explicit
/// canonical receiving-credit envelope. Each pressure case enters backoff
/// holding its original full payload and both alarms; a separate control below
/// fills the maximum payload that can still fund the next provider credit. Credits reserve
/// space without allocating; emitted concrete Turn/prompt/yield copies belong to
/// their receivers and are dropped under the shared meter's handoff convention.
fn fill(original: &Limits, route: Route, full_service: bool, bound: u64) {
    let pressure = original.history_bytes;
    let block = size(size_of::<Block>());
    // Each original route reaches three held messages; the full-service
    // supplement adds one assistant and one caller message. Two more cells
    // must remain for the provider's next assistant and possible results.
    let held_messages = 3_u32.checked_add(if full_service { 2 } else { 0 }).expect("bounded story messages");
    let messages = held_messages.checked_add(2).expect("checked provider message-cell reserve");
    let (limits, spec_cost, output, field) = pressure_limits(original, route, messages);
    let env = Env { now: Time::ZERO, wall: Wall::EPOCH, limits };
    let mut out = Queue::with_capacity(max_out(&limits));
    let count = usize::try_from(limits.sessions).expect("bounded session count");
    let mut observed = vec![(false, 0_u32, 0_u32, 0_u32, false); count];
    let meter = Meter::new();
    let mut domain = Domain::new(&limits, 1);
    let mut step = |event: Event| -> Option<Asked> {
        let may_rest = matches!(route, Route::Invalid) && matches!(event, Event::Completed { .. });
        meter.start();
        while domain.pop_fact().is_some() {}
        smith_domain_session::step(&mut domain, &env, event, &mut out);
        let measured = meter.end();
        let mut asked = observe_fill(&mut out, &mut observed);
        meter.check(measured, bound, &limits);
        if may_rest {
            domain.reclaim();
        }
        if domain.is_ready() {
            meter.start();
            while domain.pop_fact().is_some() {}
            smith_domain_session::resume(&mut domain, &env, &mut out);
            let measured = meter.end();
            asked = observe_fill(&mut out, &mut observed).or(asked);
            meter.check(measured, bound, &limits);
        }
        asked
    };
    for opener in 0..limits.sessions {
        let opener = Token::new(u64::from(opener));
        let Some(Asked::Complete { owner }) = step(Event::Open { opener, opening: zero_opening(fill_spec(&limits)) })
        else {
            panic!("the original spec and explicit canonical credit fit");
        };
        match route {
            Route::Tool => {
                let path = Path { absolute: false, parts: Box::new([Part::Name { name: name() }]) };
                let call = Decoded::Owned { call: Call::Read { path, offset: 1, window: ToolBudget::Default } };
                let content =
                    Box::new([Block::ToolCall { id: bytes(1), name: bytes(1), input: bytes(1), call, replay: None }]);
                let completion = received(content, Stop::ToolUse);
                let Some(Asked::Io { owner: op }) = step(Event::Completed { owner, completion }) else {
                    panic!("the original maximum read has full reserved receiving space");
                };
                let Some(Asked::Complete { .. }) =
                    step(Event::Done { owner: op, done: Done::Loaded { content: bytes(output), version: VERSION } })
                else {
                    panic!("original exact-payload result leaves canonical provider credit");
                };
            }
            Route::Invalid => {
                let call = Decoded::Invalid { descriptor: None, problem: Problem::Missing { field: bytes(field) } };
                let content =
                    Box::new([Block::ToolCall { id: bytes(1), name: bytes(1), input: bytes(1), call, replay: None }]);
                let completion = received(content, Stop::ToolUse);
                let Some(Asked::Complete { .. }) = step(Event::Completed { owner, completion }) else {
                    panic!("the original maximum problem and exact repeated answer fit");
                };
            }
            Route::Talk => {
                let message = pressure - spec_cost - (block + 1) - block;
                let content = Box::new([Block::Text { text: bytes(1), replay: None }]);
                let completion = received(content, Stop::EndTurn);
                let Some(Asked::Other) = step(Event::Completed { owner, completion }) else {
                    panic!("the original one-byte answer yields");
                };
                let Some(Asked::Complete { .. }) = step(Event::Continue { session: owner, content: bytes(message) })
                else {
                    panic!("original exact-payload continuation leaves canonical provider credit");
                };
            }
        }
        if full_service {
            fill_service_tail(&mut step, &limits, route, owner, pressure, (spec_cost, field));
        } else {
            assert!(
                step(Event::Failed {
                    retry_ok: true,
                    owner,
                    failure: Failure::Overloaded,
                    evidence: smith_domain_session::llm::Evidence::Unknown,
                    detail: Box::default()
                })
                .is_none(),
                "the original maximum generated payload backs off with both alarms"
            );
        }
    }
    let turns = if full_service { 2 } else { 1 };
    assert!(observed.iter().all(|&(opened, used, recorded, priced, ended)| opened
        && used == turns
        && recorded == turns
        && priced >= turns
        && !ended));
    assert_eq!(domain.sessions(), limits.sessions, "every session slot is held");
    assert_retained_payload(&meter, &limits, route, full_service, pressure);
}

fn received(content: Box<[Block]>, stop: Stop) -> Completion {
    Completion { reasoning_dropped: Box::default(), content, stop, usage: Usage::ZERO }
}

fn assert_retained_payload(meter: &Meter, limits: &Limits, route: Route, full_service: bool, pressure: u64) {
    let payload = if full_service { limits.history_bytes } else { pressure };
    // An all-invalid batch resumes after reclaim, so full-service terminal
    // payloads of different sessions do not coexist.
    let simultaneous = if full_service && matches!(route, Route::Invalid) { 1 } else { limits.sessions };
    assert!(
        meter.held() >= u64::from(simultaneous) * payload,
        "{route:?}, full_service={full_service}, {limits:?}: held {} below target {}",
        meter.held(),
        u64::from(simultaneous) * payload
    );
}

/// Supplement every original allocation route by filling the entire service
/// byte cap, with provider/continue handoffs and independent message room.
fn fill_service_tail(
    step: &mut impl FnMut(Event) -> Option<Asked>,
    limits: &Limits,
    route: Route,
    owner: Token,
    pressure: u64,
    charges: (u64, u64),
) {
    let block = size(size_of::<Block>());
    // The original route's full pressure is retained, then an accepted
    // one-byte text answer yields. A final caller-owned continuation
    // fills every remaining byte of the provisioned service envelope.
    // The next request asks for a compaction, independently of message
    // room. Its retry holds the full history beside the backoff maximum.
    let content = Box::new([Block::Text { text: bytes(1), replay: None }]);
    assert!(
        matches!(
            step(Event::Completed {
                owner,
                completion: Completion {
                    reasoning_dropped: Box::default(),
                    content,
                    stop: Stop::EndTurn,
                    usage: Usage::ZERO
                }
            }),
            Some(Asked::Other)
        ),
        "the full-pressure history yields before final padding"
    );
    let retained = match route {
        Route::Tool | Route::Talk => pressure,
        Route::Invalid => charges.0 + block + 3 + block + 1 + 2 * charges.1,
    };
    let held_messages = 3_u32 + 1 + 1;
    assert!(
        limits.history_messages.checked_sub(held_messages).expect("counted actual held messages") >= 2,
        "exact byte pressure has room for next assistant and result messages"
    );
    let padding = limits
        .history_bytes
        .checked_sub(retained + block + 1 + block)
        .expect("full service can hold its final caller message");
    assert!(
        matches!(step(Event::Continue { session: owner, content: bytes(padding) }), Some(Asked::Complete { .. })),
        "the exact full service asks for a compaction"
    );
    assert!(
        step(Event::Failed {
            retry_ok: true,
            owner,
            failure: Failure::Overloaded,
            evidence: smith_domain_session::llm::Evidence::Unknown,
            detail: Box::default()
        })
        .is_none()
    );
}

fn zero_opening(spec: Spec) -> Box<smith_domain_session::record::Opening> {
    Box::new(smith_domain_session::record::Opening {
        window_llm: None,
        spec,
        dialect: 2,
        prices: smith_domain_session::record::Prices { input: 0, cached: 0, cache_write: None, output: 0, unit: 1 },
        budget: 1,
        transcript: None,
        answered: Box::default(),
    })
}

/// Caller-owned input with the same exact byte charge in every fill route.
fn fill_spec(limits: &Limits) -> Spec {
    Spec {
        backend: smith_domain_session::record::Backend::Direct,
        effort: None,
        final_turn: None,
        window: u32::MAX,
        line: u64::from(u32::MAX) - 1,
        summary: b"Summarise the work so far.".as_slice().into(),
        preamble: b"Earlier window summary:".as_slice().into(),
        affinity: smith_domain_session::llm::Affinity { key: [0; 16], thread: 0 },
        protocol_allowance: 0,
        progress: smith_domain_session::Progress { head: Duration::from_secs(30), idle: Duration::from_secs(30) },
        account: Some(0),
        endpoint: Endpoint(0),
        model: bytes(1),
        system: bytes(1),
        authority: authority(),
        delegated: Box::new([
            Descriptor { ticket: Token::new(1), effect: Effect::Write },
            Descriptor { ticket: Token::new(2), effect: Effect::Read },
        ]),
        prompt: bytes(1),
        output: 1,
        budget: limits.budget,
    }
}

